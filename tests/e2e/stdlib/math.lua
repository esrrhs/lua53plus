local H = require("harness")

H.case("basic math", function()
  H.eq(math.abs(-3), 3)
  H.eq(math.floor(3.7), 3)
  H.eq(math.ceil(3.2), 4)
  H.eq(math.max(1,5,3), 5)
  H.eq(math.min(1,5,3), 1)
  H.eq(math.sqrt(9), 3.0)
  H.near(math.sin(0), 0)
  H.near(math.cos(0), 1)
end)

H.case("integer helpers", function()
  H.eq(math.tointeger(3.0), 3)
  H.eq(math.tointeger(3.5), nil)
  H.eq(math.type(3), "integer")
  H.eq(math.type(3.0), "float")
  H.ok(math.ult(1, -1))  -- unsigned: 1 < 2^64-1
  H.eq(math.ult(-1, 1), false)
end)

H.case("modf frexp random", function()
  local i, f = math.modf(3.75)
  H.eq(i, 3); H.near(f, 0.75)
  math.randomseed(123)
  local a = math.random()
  math.randomseed(123)
  local b = math.random()
  H.eq(a, b)
  local r = math.random(1, 10)
  H.ok(r >= 1 and r <= 10)
end)

H.case("constants", function()
  H.ok(math.pi > 3.14 and math.pi < 3.15)
  H.ok(math.huge > 1e308)
  H.ok(math.maxinteger > 0)
  H.ok(math.mininteger < 0)
end)
