local H = require("harness")

H.case("temp file write read seek", function()
  local path = os.tmpname()
  local f = assert(io.open(path, "w+"))
  f:write("hello\n", "world")
  f:flush()
  f:seek("set", 0)
  H.eq(f:read("*l"), "hello")
  H.eq(f:read("*a"), "world")
  f:close()
  local f2 = assert(io.open(path, "r"))
  H.eq(f2:read(5), "hello")
  f2:close()
  os.remove(path)
end)

H.case("lines iterator", function()
  local path = os.tmpname()
  local f = assert(io.open(path, "w"))
  f:write("a\nb\nc\n")
  f:close()
  local rows = {}
  for line in io.lines(path) do rows[#rows+1] = line end
  H.deepeq(rows, {"a","b","c"})
  os.remove(path)
end)

H.case("type of file handles", function()
  H.eq(io.type(io.stdout), "file")
  local path = os.tmpname()
  local f = assert(io.open(path, "w"))
  H.eq(io.type(f), "file")
  f:close()
  H.eq(io.type(f), "closed file")
  os.remove(path)
end)
