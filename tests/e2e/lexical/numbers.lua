local H = require("harness")

H.case("decimal integers and floats", function()
  H.eq(42, 42)
  H.eq(type(42), "number")
  H.eq(math.type(42), "integer")
  H.eq(math.type(42.0), "float")
  H.eq(3.14, 3.14)
  H.eq(.5, 0.5)
  H.eq(1e3, 1000.0)
  H.eq(1.5e-1, 0.15)
end)

H.case("hex integers and floats", function()
  H.eq(0x10, 16)
  H.eq(0XFF, 255)
  H.eq(0x1p4, 16.0)
  H.near(0x1.1p0, 1 + 1/16)
  H.eq(0x0.1p4, 1.0)
end)

H.case("integer overflow wraps / float promotion rules", function()
  H.eq(math.maxinteger + 1, math.mininteger)
  H.eq(math.mininteger - 1, math.maxinteger)
  H.eq(math.type(1 + 0.0), "float")
  H.eq(math.type(1 // 1), "integer")
end)

H.case("tonumber bases", function()
  H.eq(tonumber("10"), 10)
  H.eq(tonumber("10", 2), 2)
  H.eq(tonumber("ff", 16), 255)
  H.eq(tonumber("0x10"), 16)
  H.eq(tonumber("1.5"), 1.5)
  H.eq(tonumber("nope"), nil)
end)
