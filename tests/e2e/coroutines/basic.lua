local H = require("harness")

H.case("create resume yield status wrap", function()
  local co = coroutine.create(function(a)
    H.eq(coroutine.status(coroutine.running()), "running")
    local b = coroutine.yield(a + 1)
    return b * 2
  end)
  H.eq(coroutine.status(co), "suspended")
  local ok, v = coroutine.resume(co, 10)
  H.ok(ok); H.eq(v, 11)
  H.eq(coroutine.status(co), "suspended")
  ok, v = coroutine.resume(co, 7)
  H.ok(ok); H.eq(v, 14)
  H.eq(coroutine.status(co), "dead")
end)

H.case("coroutine.wrap", function()
  local f = coroutine.wrap(function()
    coroutine.yield(1)
    coroutine.yield(2)
    return 3
  end)
  H.eq(f(), 1)
  H.eq(f(), 2)
  H.eq(f(), 3)
end)

H.case("isyieldable", function()
  H.ok(coroutine.isyieldable() == false or coroutine.isyieldable() == true)
  local co = coroutine.create(function()
    return coroutine.isyieldable()
  end)
  local ok, y = coroutine.resume(co)
  H.ok(ok); H.eq(y, true)
end)
