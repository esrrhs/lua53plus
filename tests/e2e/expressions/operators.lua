local H = require("harness")

H.case("arithmetic", function()
  H.eq(1 + 2 * 3, 7)
  H.eq((1 + 2) * 3, 9)
  H.eq(10 - 3, 7)
  H.eq(10 / 4, 2.5)
  H.eq(10 // 4, 2)
  H.eq(10 % 4, 2)
  H.eq(2 ^ 3, 8.0)
  H.eq(- -3, 3)
end)

H.case("bitwise", function()
  H.eq(0xF & 0x3, 0x3)
  H.eq(0x1 | 0x2, 0x3)
  H.eq(0xF ~ 0xA, 0x5)
  H.eq(~0, -1)
  H.eq(1 << 4, 16)
  H.eq(16 >> 2, 4)
end)

H.case("relational and length", function()
  H.ok(3 < 4)
  H.ok(4 >= 4)
  H.ok("a" < "b")
  H.eq(# {1,2,3}, 3)
  H.eq(# "hi", 2)
end)

H.case("equality and identity", function()
  H.ok(1 == 1.0)
  H.ok(1 ~= 2)
  H.ok({} ~= {})
  local t = {}
  H.ok(t == t)
  H.ok(rawequal(1, 1))
end)
